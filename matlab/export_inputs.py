"""Готує вхідні дані для звірки з MATLAB/IRIS: ті самі оброблені дані, параметри та план прогнозу.

Запуск з кореня репозиторію:  python matlab/export_inputs.py
Далі в MATLAB:                 cd matlab; run_check
Порівняння:                    python matlab/compare_with_matlab.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import config as cfg  # noqa: E402
from qpm import pipeline  # noqa: E402
from qpm.data import write_iris_csv  # noqa: E402

OUT = ROOT / "matlab" / "inputs"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    ctx = pipeline.prepare(cfg)
    dq = ctx["dq"].copy()
    # domestic data after LAST_HIST hidden exactly as in pipeline.prepare
    after = dq.index > pd.Period(cfg.LAST_HIST, "Q")
    for col in pipeline.DOMESTIC_OBS:
        dq.loc[after, col] = np.nan
    cols = ["L_GDP", "L_CPI", "IR_POLICY", "L_ER", "IR_EA", "L_CPI_EA", "L_GDP_EA_GAP", "L_GDP_GAP"]
    write_iris_csv(dq[cols], OUT / "dq_python.csv")

    # parameters -> MATLAB function
    p = yaml.safe_load((ROOT / cfg.PARAMS_FILE).read_text(encoding="utf-8"))
    std = p.pop("std")
    lines = ["function p = param_check()", "% generated by matlab/export_inputs.py from model/params.yaml"]
    lines += [f"p.{k} = {v};" for k, v in p.items()]
    lines += [f"p.std_{k} = {v};" for k, v in std.items()]
    lines += ["end", ""]
    (ROOT / "matlab" / "param_check.m").write_text("\n".join(lines), encoding="utf-8")

    # forecast plan: exogenized variables (var, period, value, shock) and judgment shocks (shock, period, value)
    plan = pipeline.with_rate_path(pipeline.base_plan(ctx), cfg.RECOMMENDED_RATE_PATH)
    endo = {}
    for shock, pers in plan.endo.items():
        for per in pers:
            endo.setdefault(per, []).append(shock)
    exo_rows = []
    pair = {"ir_ea": "res_ir_ea", "l_gdp_ea_gap": "res_l_gdp_ea_gap", "dl_cpi_ea": "res_dl_cpi_ea",
            "l_cpi": "res_dl_cpi", "dl_er_tar": "res_dl_er_tar", "ir_pol": "res_ir_tlr"}
    for var, d in plan.exo.items():
        for per, val in d.items():
            exo_rows.append({"var": var, "period": str(per), "value": float(val), "shock": pair[var]})
    pd.DataFrame(exo_rows).to_csv(OUT / "plan_exogenized.csv", index=False)
    shock_rows = [{"shock": s, "period": str(per), "value": float(v)} for s, d in plan.shocks.items() for per, v in d.items()]
    pd.DataFrame(shock_rows).to_csv(OUT / "plan_shocks.csv", index=False)
    (OUT / "ranges.txt").write_text(f"{cfg.FIRST_HIST}\n{cfg.LAST_HIST}\n{cfg.LAST_FORE}\n", encoding="utf-8")

    # python results for comparison
    ctx["filt"].vars.to_csv(OUT / "filter_python.csv")
    pipeline.run(ctx, plan).to_csv(OUT / "forecast_python.csv")
    print("Готово:", sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
