"""Готує вхідні дані для MATLAB/IRIS: ті самі оброблені дані, параметри та плани всіх сценаріїв.

Запуск з кореня репозиторію:  python matlab/export_inputs.py
Далі в MATLAB:                 cd matlab; run_check
Порівняння:                    python matlab/compare_with_matlab.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import config as cfg  # noqa: E402
from qpm import pipeline  # noqa: E402
from qpm.data import write_iris_csv  # noqa: E402

OUT = ROOT / "matlab" / "inputs"
OBS = ["L_GDP", "L_CPI", "L_CPI_C", "IR_POLICY", "L_ER", "IR_EA", "L_CPI_EA", "L_GDP_EA_GAP", "L_ROIL", "L_GDP_GAP"]


def scenario_plans(ctx):
    """Exactly the plans run_forecast.py uses: baseline with the recommended decision; scenarios on top."""
    return pipeline.scenario_plans(ctx)


def write_plan(plan, k):
    exo = [{"var": v, "period": str(p), "value": float(x)} for v, d in plan.exo.items() for p, x in d.items()]
    endo = [{"shock": s, "period": str(p)} for s, ps in plan.endo.items() for p in sorted(ps)]
    shocks = [{"shock": s, "period": str(p), "value": float(x)} for s, d in plan.shocks.items() for p, x in d.items()]
    pd.DataFrame(exo, columns=["var", "period", "value"]).to_csv(OUT / f"plan{k}_exo.csv", index=False)
    pd.DataFrame(endo, columns=["shock", "period"]).to_csv(OUT / f"plan{k}_endo.csv", index=False)
    pd.DataFrame(shocks, columns=["shock", "period", "value"]).to_csv(OUT / f"plan{k}_shocks.csv", index=False)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("plan*.csv"):
        old.unlink()
    ctx = pipeline.prepare(cfg)
    dq = ctx["dq"].copy()
    after = dq.index > pd.Period(cfg.LAST_HIST, "Q")
    for col in pipeline.DOMESTIC_OBS:
        dq.loc[after, col] = np.nan
    write_iris_csv(dq[OBS], OUT / "dq_python.csv")

    p = yaml.safe_load((ROOT / cfg.PARAMS_FILE).read_text(encoding="utf-8"))
    std = p.pop("std")
    lines = ["function p = param_check()", "% generated by matlab/export_inputs.py from model/params.yaml"]
    lines += [f"p.{k} = {v};" for k, v in p.items()]
    lines += [f"p.std_{k} = {v};" for k, v in std.items()]
    lines += ["end", ""]
    (ROOT / "matlab" / "param_check.m").write_text("\n".join(lines), encoding="utf-8")

    plans = scenario_plans(ctx)
    names = list(plans)
    for k, name in enumerate(names, start=1):
        write_plan(plans[name], k)
        pipeline.run(ctx, plans[name]).to_csv(OUT / f"forecast{k}_python.csv")
    (OUT / "scenarios.txt").write_text("\n".join(names) + "\n", encoding="utf-8")
    (OUT / "ranges.txt").write_text(f"{cfg.FIRST_HIST}\n{cfg.LAST_HIST}\n{cfg.LAST_FORE}\n", encoding="utf-8")
    ctx["filt"].vars.to_csv(OUT / "filter_python.csv")
    print("Готово:", len(names), "сценаріїв;", sorted(x.name for x in OUT.iterdir())[:6], "...")


if __name__ == "__main__":
    main()
