def scenario_hard_winter(plan, f, ctx=None):
    """«Важка зима»: масовані удари по генерації, відключення, імпорт е/е та газу — свідомо м'якша за зиму 2024/25.

    Опора — згладжені шоки фільтра за зиму 2024/25 (III кв. 2024 – I кв. 2025): небазові ціни +5,1 / +2,8, базова
    +2,7 / +4,4 (IV кв. 2024 – I кв. 2025), попит −1,7 / −1,2, премія до 2,1. Сценарій бере приблизно половину:
    (1) частина енергетичного тиску вже в базовому (адмінціни +1,2 / +1,1, шок витрат +0,8 / +0,4 — `JUDGMENTS`);
    (2) очікуваний дефіцит потужності цієї зими — ≈3 ГВт у звичайному режимі й до 5 ГВт у пік (оцінки експертів,
    The Page, жовтень 2026) проти ≈9 ГВт втраченої генерації навесні 2024 (Укренерго), тобто система краще
    підготовлена, хоч і без запасу міцності. Чутливість лінійна: удвічі більші шоки — удвічі більший ефект."""
    # тарифи на е/е й тепло, імпорт енергії: ≈половина шоку небазових цін зими 2024/25 (+5,1 / +2,8), 1,1σ / 0,4σ
    plan.shock("res_dl_rnc", [f + 1, f + 2], [3.0, 1.0])
    # витрати бізнесу (генератори, логістика): НБУ оцінює вторинні ефекти атак у +0,4–0,6 в. п. до річної інфляції
    # (ІЗ, липень 2026); +1,0 / +0,5 кв/кв у річному вимірі дають ≈+0,4 в. п. поверх того, що вже в базовому
    plan.shock("res_dl_cpi_c", [f + 1, f + 2], [1.0, 0.5])
    # відключення, падіння виробництва: ≈половина шоків попиту зими 2024/25 (−1,7 / −1,2); сума −1,8 ≈ 0,8σ
    plan.shock("res_l_gdp_gap", [f, f + 1, f + 2], [-0.6, -0.8, -0.4])
    # вищий попит на валюту (імпорт енергії, обладнання): премія як у II–III кв. 2025 (2,4 / 2,1), затухає
    plan.shock("res_prem_uip_gap", [f, f + 1], [1.5, 1.0])
    return plan


def scenario_funding_gap(plan, f, ctx=None):
    """«Дефіцит фінансування»: частина потреби 2027 р. не закривається, тиск на резерви → послаблення гривні.

    Розмір дірки: проєкт бюджету-2027 (№16000, 15.09.2026) — потреба в міжнародному фінансуванні $52,6 млрд, з них
    підтверджено ≈$20 млрд (Підласа, вересень 2026), без джерела ≈$32,6 млрд. Kiel Institute (Ukraine Support
    Tracker, 13.08.2026): фінансова й гуманітарна допомога в I півріччі 2026 у середньому за місяць на 41% менша, ніж
    у 2025. Якщо так само недоотримати непокритий залишок — ≈0,41 × 32,6 ≈ $13 млрд за рік; кредит ЄС €90 млрд
    розписаний лише на 2026–2027. Резерви на 1.10.2026 — ≈$47 млрд (≈4 місяці імпорту), тож $13–20 млрд без
    компенсації означають послаблення, а не просто витрату резервів."""
    rng = [f + i for i in range(4)]
    # цільовий курс: ≈+9% послаблення за рік, як у 2024 (38 → 42 грн/$ за затримки допомоги США), спадним темпом
    plan.exogenize("dl_er_tar", rng, [12, 10, 8, 6])
    plan.endogenize("res_dl_er_tar", rng)
    # премія за ризик: пряме відтворення епізоду I–III кв. 2024 (зависла допомога США) — згладжені шоки фільтра
    # res_prem_uip_gap 1,60 / 1,83 / 2,10 (до 25.10 стояло 2,0 / 1,5 / 1,0 — та сама сума, інший профіль)
    plan.shock("res_prem_uip_gap", [f, f + 1, f + 2], [1.6, 1.8, 2.1])
    # секвестр невоєнних видатків: дірка ≈$13 млрд ≈ 5% ВВП; за фіскального мультиплікатора ≈0,3–0,5 для поточних
    # видатків в Україні (Вдовиченко, Вісник НБУ 2018, №244) це ≈−1,5–2,5 в. п. до розриву ВВП, розтягнуто на 4
    # квартали (сума −3,1 за рік, спадним профілем; кожен шок < 0,5σ)
    plan.shock("res_l_gdp_gap", [f + 1, f + 2, f + 3, f + 4], [-0.8, -1.0, -0.8, -0.5])
    return plan


def scenario_favourable(plan, f, ctx=None):
    """«Сприятливий»: прогрес у мирних переговорах, ритмічна допомога, зниження ризиків — дзеркало «Важкої зими» за
    масштабом (ті самі ≈0,5σ), щоб набір сценаріїв не був зміщений в один бік."""
    # премія за ризик: зниження на величину, яку фільтр показував після ухвалення допомоги у 2024 (з 2,1 до ≈0,2)
    plan.shock("res_prem_uip_gap", [f + 1, f + 2, f + 3], [-1.5, -1.5, -1.0])
    # нормалізація енергетики й логістики: знімає шок витрат базового (+0,8 / +0,4) і трохи більше — ≈0,3σ
    plan.shock("res_dl_cpi_c", [f + 1, f + 2, f + 3], [-1.0, -0.7, -0.5])
    # відбудова, повернення мігрантів: ≈половина (за модулем) шоків попиту «Важкої зими», з лагом у квартал
    plan.shock("res_l_gdp_gap", [f + 2, f + 3, f + 4], [0.4, 0.4, 0.3])
    return plan


