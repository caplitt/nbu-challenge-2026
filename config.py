def scenario_hard_winter(plan, f, ctx=None):
    """«Важка зима»: масовані удари по генерації, відключення, імпорт е/е та газу."""
    plan.shock("res_dl_rnc", [f + 1, f + 2], [3.0, 1.0])          # тарифи на е/е й тепло, імпорт енергії
    plan.shock("res_dl_cpi_c", [f + 1, f + 2], [1.0, 0.5])        # витрати бізнесу (генератори, логістика)
    plan.shock("res_l_gdp_gap", [f, f + 1, f + 2], [-0.6, -0.8, -0.4])  # відключення, падіння виробництва
    plan.shock("res_prem_uip_gap", [f, f + 1], [1.5, 1.0])        # вищий попит на валюту (імпорт енергії)
    return plan


def scenario_funding_gap(plan, f, ctx=None):
    """«Дефіцит фінансування»: затримка $15–20 млрд допомоги до II кв. 2027, тиск на резерви → послаблення гривні."""
    rng = [f + i for i in range(4)]
    plan.exogenize("dl_er_tar", rng, [12, 10, 8, 6])              # ≈ +9% девальвації за рік
    plan.endogenize("res_dl_er_tar", rng)
    plan.shock("res_prem_uip_gap", [f, f + 1, f + 2], [2.0, 1.5, 1.0])
    plan.shock("res_l_gdp_gap", [f + 1, f + 2, f + 3, f + 4], [-0.8, -1.0, -0.8, -0.5])  # секвестр невоєнних видатків
    return plan


def scenario_favourable(plan, f, ctx=None):
    """«Сприятливий»: прогрес у мирних переговорах, ритмічна допомога, зниження ризиків."""
    plan.shock("res_prem_uip_gap", [f + 1, f + 2, f + 3], [-1.5, -1.5, -1.0])
    plan.shock("res_dl_cpi_c", [f + 1, f + 2, f + 3], [-1.0, -0.7, -0.5])  # нормалізація енергетики й логістики
    plan.shock("res_l_gdp_gap", [f + 2, f + 3, f + 4], [0.4, 0.4, 0.3])  # відбудова, повернення мігрантів
    return plan


